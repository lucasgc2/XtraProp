_language = "en"


def set_language(code):
    global _language
    _language = code if code in STRINGS else "en"


def get_language():
    return _language


def t(key, **kwargs):
    """Translated string for key, formatted with kwargs."""
    text = STRINGS[_language].get(key, STRINGS["en"].get(key, key))
    return text.format(**kwargs) if kwargs else text


def field_label(name):
    return t("field." + name)
